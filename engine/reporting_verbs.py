"""Bounded financial reporting constructions, never global stop words."""
import re

VERBS = {'record', 'records', 'recorded', 'generate', 'generates', 'generated'}
FLOW = {'revenue', 'operating_income', 'net_income'}


def license_reporting(question, items, view, glossary=()):
    types = [view(it)['phrase_type'] for it in items]
    if types.count('entity') != 1 or types.count('metric') != 1:
        return
    m, e = types.index('metric'), types.index('entity')
    metric = view(items[m])['valid_phrase']
    if metric not in FLOW:
        return
    word = lambda n: question[items[n]['ch0']:items[n]['ch1']].casefold()
    from seed_vocabulary import reporting_forms
    imported = reporting_forms(glossary)
    candidates = [n for n in range(len(items)) if word(n) in VERBS | imported.keys()
                  and types[n] in {'unlisted', 'grammar', 'seed_construction'}]
    if len(candidates) != 1:
        return
    v = candidates[0]
    # Amount WH inversion: what [metric] did [company] generate ... ?
    prefix = question[:items[m]['ch0']].strip().casefold()
    middle = [word(n) for n in range(m + 1, e)]
    wh = (m < e < v and prefix in {'what', 'how much', 'what amount of'}
          and middle in (['did'], ['does'], ['do'], ['has'], ['had'], ['have'])
          and all(word(n) in {"'s", '’s'} for n in range(e + 1, v)))
    # Boolean inversion requires an explicit comparison, not existence.
    cmp = (e < v < m and question[:items[e]['ch0']].strip().casefold() in {'did', 'does', 'do'}
           and all(word(n) in {"'s", '’s'} for n in range(e + 1, v))
           and v + 1 == m and types.count('compare_op') == types.count('quantity') == 1)
    # Passive measure request: what revenue was generated by Company ...
    passive = (m < v < e and prefix in {'what', 'how much', 'what amount of'}
               and [word(n) for n in range(m + 1, v)] in (['was'], ['is'], ['has', 'been'], ['had', 'been'])
               and [word(n) for n in range(v + 1, e)] == ['by']
               and (word(v) in {'recorded', 'generated'} or imported.get(word(v), {}).get('form') == 'participle'))
    # A licensed request construction can select an explicit reporting clause.
    request = (m < e < v and any(it.get('construction_role') == 'request' for it in items[:m])
               and middle in ([], ['that'], ['which'])
               and all(word(n) in {"'s", '’s'} for n in range(e + 1, v)))
    if wh or cmp or passive or request:
        items[v].update(ptype='grammar', seg_type='filler', consumed=True,
                        reporting_role='financial_measure_verb',
                        **({'seed_mapping': imported[word(v)]['mapping_id']} if word(v) in imported else {}))
